// Compress example poster images for the landing-page gallery.
//
// Input  (NOT committed): assets-raw/examples/<group>/*.{png,jpg,jpeg,webp}
// Output (committed):      public/examples/<group>/*.webp  +  lib/data/examples.ts
//
// Run:  npm run compress:examples
import { readdir, mkdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = process.cwd();
const RAW = path.join(ROOT, "assets-raw", "examples");
const OUT = path.join(ROOT, "public", "examples");
const GROUPS = [
  { key: "chichi", label: "Chichi Kelinci" },
  { key: "lainnya", label: "Hasil" },
];
const MAX_WIDTH = 1080;
const QUALITY = 80;
const IMG_EXT = /\.(png|jpe?g|webp)$/i;

function slug(name) {
  return name
    .toLowerCase()
    .replace(/\.[^.]+$/, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

async function processGroup({ key, label }) {
  const rawDir = path.join(RAW, key);
  if (!existsSync(rawDir)) {
    console.warn(`[skip] folder tidak ada: ${path.relative(ROOT, rawDir)}`);
    return [];
  }
  const outDir = path.join(OUT, key);
  await mkdir(outDir, { recursive: true });

  const files = (await readdir(rawDir))
    .filter((f) => IMG_EXT.test(f))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

  const manifest = [];
  for (const file of files) {
    const out = `${slug(file)}.webp`;
    await sharp(path.join(rawDir, file))
      .rotate()
      .resize({ width: MAX_WIDTH, withoutEnlargement: true })
      .webp({ quality: QUALITY })
      .toFile(path.join(outDir, out));
    manifest.push({ src: `/examples/${key}/${out}`, alt: `${label} — ${slug(file)}` });
    console.log(`  ✓ ${file} -> ${key}/${out}`);
  }
  return manifest;
}

const chichi = await processGroup(GROUPS[0]);
const other = await processGroup(GROUPS[1]);

const ts = `// AUTO-GENERATED by scripts/compress-examples.mjs — do not edit by hand.
export interface ExampleImage {
  src: string;
  alt: string;
}

export const CHICHI_TIKTOK_URL = "https://www.tiktok.com/@chichi.kelinci";

export const CHICHI_EXAMPLES: ExampleImage[] = ${JSON.stringify(chichi, null, 2)};

export const OTHER_EXAMPLES: ExampleImage[] = ${JSON.stringify(other, null, 2)};
`;

await mkdir(path.join(ROOT, "lib", "data"), { recursive: true });
await writeFile(path.join(ROOT, "lib", "data", "examples.ts"), ts, "utf8");

console.log(
  `\nSelesai: ${chichi.length} chichi + ${other.length} lainnya -> lib/data/examples.ts`,
);
